import * as XLSX from 'xlsx';

/**
 * Auto-fits columns in a worksheet based on content length
 */
function autoFitColumns(rows, ws) {
  if (!rows || rows.length === 0) return;
  const colKeys = Object.keys(rows[0]);
  ws['!cols'] = colKeys.map((key) => {
    let maxLen = key.length;
    rows.forEach((r) => {
      const val = r[key] != null ? String(r[key]) : '';
      if (val.length > maxLen) {
        maxLen = Math.min(val.length, 55);
      }
    });
    return { wch: Math.max(maxLen + 3, 12) };
  });
}

/**
 * Exports quotation and sales invoice records to a multi-sheet Excel (.xlsx) workbook.
 * 
 * @param {Array} records - Array of quote / invoice records to export
 * @param {Object} companySettings - Company settings from Admin Config
 * @param {String} filterLabel - Current filter label (e.g., 'All', 'Pending Review', 'Approved', 'Sales Invoices')
 */
export function exportQuotesToExcel(records = [], companySettings = {}, filterLabel = 'All') {
  if (!records || records.length === 0) {
    alert('No quotation or sales invoice records found to export.');
    return false;
  }

  try {
    const wb = XLSX.utils.book_new();

    // =========================================================
    // 1. SHEET 1: Master Quotes & Invoices Ledger
    // =========================================================
    const ledgerRows = records.map((rec) => {
      const isInvoice = rec.type === 'sales_invoice';
      const isApproved = !isInvoice && rec.status === 'Approved';

      // Machine names and counts summary
      const machineNames = (rec.items || [])
        .map((it) => {
          const name = it.product?.name || it.name || 'Machine';
          const qty = it.quantity || 1;
          return `${name} (x${qty})`;
        })
        .join('; ');

      // Total additional charges
      const totalAddCharges = (rec.additionalCharges || []).reduce(
        (sum, c) => sum + (Number(c.amount) || 0),
        0
      );

      const subtotalVal = Math.round((Number(rec.subtotal) || 0) * 100) / 100;
      const vatVal = Math.round((Number(rec.vat) || 0) * 100) / 100;
      const grandTotalVal = Math.round((Number(rec.grandTotal) || 0) * 100) / 100;

      return {
        'Doc ID': isInvoice ? (rec.invoiceNumber || rec.id) : rec.id,
        'Base Quote ID': rec.id || '-',
        'Invoice Number': rec.invoiceNumber || (isInvoice ? rec.id : '-'),
        'Doc Type': isInvoice ? 'Sales Invoice' : 'Quotation',
        'Status': isInvoice ? 'Sales Invoice' : (rec.status || 'Pending Review'),
        'Customer Name': rec.customerName || '-',
        'Contact Person': rec.contactPerson || '-',
        'Contact Phone': rec.contactNumber || '-',
        'Customer Details': rec.customerDetails || '-',
        'Date': isInvoice && rec.invoiceDate ? rec.invoiceDate : (rec.date || '-'),
        'Quotation Date': rec.date || '-',
        'Invoice Date': rec.invoiceDate || (isInvoice ? rec.date : '-'),
        'Created By': rec.createdBy || 'Sales Agent',
        'Approved By': (isApproved || isInvoice) ? (rec.approvedBy || 'Finance Officer') : 'Pending',
        'Invoice Generated By': isInvoice ? (rec.invoiceGeneratedBy || rec.createdBy || 'Finance Agent') : '-',
        'Sales Officer': rec.salesOfficer || '-',
        'Payment Terms': rec.selectedTerms?.name || '-',
        'Machines Count': rec.items?.length || 0,
        'Machines Summary': machineNames || '-',
        'Additional Charges (AED)': Math.round(totalAddCharges * 100) / 100,
        'Subtotal (AED)': subtotalVal,
        'VAT 5% (AED)': vatVal,
        'Grand Total (AED)': grandTotalVal,
      };
    });

    // Summary Row
    const totalSubtotal = ledgerRows.reduce((sum, r) => sum + (Number(r['Subtotal (AED)']) || 0), 0);
    const totalVat = ledgerRows.reduce((sum, r) => sum + (Number(r['VAT 5% (AED)']) || 0), 0);
    const totalGrand = ledgerRows.reduce((sum, r) => sum + (Number(r['Grand Total (AED)']) || 0), 0);
    const totalMachines = ledgerRows.reduce((sum, r) => sum + (Number(r['Machines Count']) || 0), 0);

    ledgerRows.push({
      'Doc ID': 'TOTAL / SUMMARY',
      'Base Quote ID': '-',
      'Invoice Number': '-',
      'Doc Type': `${records.length} Records Exported`,
      'Status': `Scope: ${filterLabel}`,
      'Customer Name': '-',
      'Contact Person': '-',
      'Contact Phone': '-',
      'Customer Details': '-',
      'Date': new Date().toLocaleDateString('en-GB'),
      'Quotation Date': '-',
      'Invoice Date': '-',
      'Created By': '-',
      'Approved By': '-',
      'Invoice Generated By': '-',
      'Sales Officer': '-',
      'Payment Terms': '-',
      'Machines Count': totalMachines,
      'Machines Summary': `${totalMachines} Total Machines Across Records`,
      'Additional Charges (AED)': '-',
      'Subtotal (AED)': Math.round(totalSubtotal * 100) / 100,
      'VAT 5% (AED)': Math.round(totalVat * 100) / 100,
      'Grand Total (AED)': Math.round(totalGrand * 100) / 100,
    });

    const wsLedger = XLSX.utils.json_to_sheet(ledgerRows);
    autoFitColumns(ledgerRows, wsLedger);
    XLSX.utils.book_append_sheet(wb, wsLedger, 'Quotes & Invoices');

    // =========================================================
    // 2. SHEET 2: Itemized Machines & Equipment Breakdown
    // =========================================================
    const itemRows = [];
    records.forEach((rec) => {
      const isInvoice = rec.type === 'sales_invoice';
      const docId = isInvoice ? (rec.invoiceNumber || rec.id) : rec.id;
      (rec.items || []).forEach((it, idx) => {
        const uPrice = Number(it.unitPrice || it.product?.price || 0);
        const oPrice = Number(it.offerPrice !== undefined ? it.offerPrice : uPrice);
        const qty = Number(it.quantity || 1);
        const lineTotal = oPrice * qty;

        itemRows.push({
          'Doc ID': docId,
          'Doc Type': isInvoice ? 'Sales Invoice' : 'Quotation',
          'Customer Name': rec.customerName || '-',
          'Date': isInvoice && rec.invoiceDate ? rec.invoiceDate : rec.date,
          'Item #': idx + 1,
          'Machine Code': it.product?.code || it.code || '-',
          'Machine Name': it.product?.name || it.name || '-',
          'Category': it.product?.category || it.category || '-',
          'Quantity': qty,
          'Unit Price (AED)': Math.round(uPrice * 100) / 100,
          'Offer Price (AED)': Math.round(oPrice * 100) / 100,
          'Total (AED)': Math.round(lineTotal * 100) / 100,
        });
      });
    });

    if (itemRows.length > 0) {
      const itemsGrandTotal = itemRows.reduce((sum, r) => sum + (Number(r['Total (AED)']) || 0), 0);
      const itemsTotalQty = itemRows.reduce((sum, r) => sum + (Number(r['Quantity']) || 0), 0);

      itemRows.push({
        'Doc ID': 'TOTAL / SUMMARY',
        'Doc Type': '-',
        'Customer Name': '-',
        'Date': '-',
        'Item #': `${itemRows.length} Line Items`,
        'Machine Code': '-',
        'Machine Name': '-',
        'Category': '-',
        'Quantity': itemsTotalQty,
        'Unit Price (AED)': '-',
        'Offer Price (AED)': '-',
        'Total (AED)': Math.round(itemsGrandTotal * 100) / 100,
      });

      const wsItems = XLSX.utils.json_to_sheet(itemRows);
      autoFitColumns(itemRows, wsItems);
      XLSX.utils.book_append_sheet(wb, wsItems, 'Itemized Breakdown');
    }

    // =========================================================
    // 3. SHEET 3: Additional Charges Breakdown (if any)
    // =========================================================
    const chargeRows = [];
    records.forEach((rec) => {
      const isInvoice = rec.type === 'sales_invoice';
      const docId = isInvoice ? (rec.invoiceNumber || rec.id) : rec.id;
      (rec.additionalCharges || []).forEach((ch) => {
        if (ch && ch.description && Number(ch.amount) > 0) {
          chargeRows.push({
            'Doc ID': docId,
            'Doc Type': isInvoice ? 'Sales Invoice' : 'Quotation',
            'Customer Name': rec.customerName || '-',
            'Description': ch.description,
            'Amount (AED)': Math.round(Number(ch.amount) * 100) / 100,
          });
        }
      });
    });

    if (chargeRows.length > 0) {
      const chargesTotal = chargeRows.reduce((sum, r) => sum + (Number(r['Amount (AED)']) || 0), 0);
      chargeRows.push({
        'Doc ID': 'TOTAL',
        'Doc Type': '-',
        'Customer Name': '-',
        'Description': `${chargeRows.length} Charges Total`,
        'Amount (AED)': Math.round(chargesTotal * 100) / 100,
      });
      const wsCharges = XLSX.utils.json_to_sheet(chargeRows);
      autoFitColumns(chargeRows, wsCharges);
      XLSX.utils.book_append_sheet(wb, wsCharges, 'Additional Charges');
    }

    // Generate filename
    const compName = (companySettings?.companyName || 'DELITRADE').replace(/[^a-zA-Z0-9]/g, '_');
    const todayStr = new Date().toISOString().split('T')[0];
    const filterTag =
      filterLabel && filterLabel !== 'ALL' && filterLabel !== 'All'
        ? `_${filterLabel.replace(/\s+/g, '_')}`
        : '';
    const fileName = `${compName}_Quotes_Invoices${filterTag}_${todayStr}.xlsx`;

    // Write file with browser download fallback
    try {
      XLSX.writeFile(wb, fileName);
    } catch {
      const wbout = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
      const blob = new Blob([wbout], {
        type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = fileName;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }

    return true;
  } catch (error) {
    console.error('Error exporting quotes to Excel:', error);
    alert('Failed to export to Excel: ' + (error.message || 'Unknown error'));
    return false;
  }
}
